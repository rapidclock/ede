/// Exact default chord before contextual routing.
pub(crate) struct Binding {
    pub code: KeyCode,
    pub modifiers: KeyModifiers,
    pub command: Command,
}
impl Binding {
    /// Build static metadata without allocation.
    const fn new(code: KeyCode, modifiers: KeyModifiers, command: Command) -> Self {
        Self {
            code,
            modifiers,
            command,
        }
    }
}
